#!/usr/bin/env python3
"""Generate .claude/rules/ files from the Copilot instruction files in .github/instructions/.

Copilot attaches each `*.instructions.md` file to the files named in its `applyTo` setting.
Claude Code does the same with rule files in `.claude/rules/` that have a `paths` setting.
This script keeps one set of source files: it reads `.github/instructions/**/*.instructions.md`
and writes one rule file per source file, with `applyTo` converted to `paths`.

Rules for the conversion:
- `applyTo: "a,b,c"` (comma-separated text) or a YAML list becomes a `paths` list.
- `applyTo: "**/*"` becomes a rule without `paths`, which Claude Code loads for every task.
- A source file without `applyTo` is skipped. Copilot loads those by matching their
  description to the task, which Claude Code cannot do. Skipped files are listed in the output.
- The Markdown body is copied, except that references to other `*.instructions.md` files are
  rewritten to point at the matching generated rule file (or, for skipped files, at the source file).
  Generated files start with a marker comment.
- Rule files that carry the marker but have no source file any more are deleted.
  Files without the marker are never changed or deleted.

Usage:
    python3 scripts/dev/sync_claude_rules.py           # write or update the rule files
    python3 scripts/dev/sync_claude_rules.py --check   # change nothing; exit 1 if files are out of date

Uses only the standard library and does not connect to any service.
"""

from __future__ import annotations

import argparse
import os
import re
import sys
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path

REPO_ROOT: Path = Path(__file__).resolve().parents[2]
SOURCE_DIR: Path = REPO_ROOT / ".github" / "instructions"
TARGET_DIR: Path = REPO_ROOT / ".claude" / "rules"

SOURCE_SUFFIX: str = ".instructions.md"
MARKER_PREFIX: str = "<!-- Generated by scripts/dev/sync_claude_rules.py from "
ALWAYS_ON_PATTERNS: frozenset[str] = frozenset({"**/*", "**"})

FRONTMATTER_END = re.compile(r"^---+\s*$")
KEY_LINE = re.compile(r"^([A-Za-z_][\w-]*):\s*(.*)$")
LIST_ITEM = re.compile(r"^\s+-\s+(.*)$")
INSTRUCTION_REF = re.compile(r"(?<![\w/.-])((?:\.{1,2}/)?(?:[\w-]+/)*[\w-]+" + re.escape(SOURCE_SUFFIX) + r")")


@dataclass(frozen=True)
class SourceFile:
    """One instruction file after its frontmatter has been read."""

    path: Path
    apply_to: list[str] | None
    body: str

    @property
    def relative(self) -> str:
        return self.path.relative_to(REPO_ROOT).as_posix()

    @property
    def target(self) -> Path:
        name: str = self.path.name[: -len(SOURCE_SUFFIX)] + ".md"
        return TARGET_DIR / self.path.parent.relative_to(SOURCE_DIR) / name


def unquote(value: str) -> str:
    """Removes one pair of matching single or double quotes around a value."""
    value = value.strip()
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        return value[1:-1]
    return value


def split_patterns(value: str) -> list[str]:
    """Splits a comma-separated pattern text into trimmed, non-empty patterns."""
    return [part.strip() for part in value.split(",") if part.strip()]


def parse_source(path: Path) -> SourceFile:
    """Reads the `applyTo` setting and the body of one instruction file.

    Understands the forms used in this repository: a quoted comma-separated text, a YAML list
    on following lines, and a closing delimiter line of three or more dashes.
    """
    lines: list[str] = path.read_text(encoding="utf-8").splitlines(keepends=True)
    if not lines or lines[0].strip() != "---":
        return SourceFile(path=path, apply_to=None, body="".join(lines))

    end: int | None = next((i for i in range(1, len(lines)) if FRONTMATTER_END.match(lines[i].rstrip("\n"))), None)
    if end is None:
        raise ValueError(f"{path}: frontmatter is not closed")

    apply_to: list[str] | None = None
    index: int = 1
    while index < end:
        match = KEY_LINE.match(lines[index].rstrip("\n"))
        index += 1
        if not match or match.group(1) != "applyTo":
            continue
        inline: str = unquote(match.group(2))
        if inline:
            apply_to = split_patterns(inline)
            continue
        items: list[str] = []
        while index < end and (item := LIST_ITEM.match(lines[index].rstrip("\n"))):
            items.extend(split_patterns(unquote(item.group(1))))
            index += 1
        apply_to = items

    return SourceFile(path=path, apply_to=apply_to or None, body="".join(lines[end + 1 :]))


def find_referenced_source(source: SourceFile, reference: str, sources: Sequence[SourceFile]) -> SourceFile | None:
    """Finds the instruction file named by a reference such as `features/loaders.instructions.md`.

    Tries the path relative to the referring file, then relative to `.github/instructions/`,
    then a unique match on the file name alone. Returns None when nothing matches.
    """
    for base in (source.path.parent, SOURCE_DIR):
        candidate: Path = (base / reference).resolve()
        for other in sources:
            if other.path.resolve() == candidate:
                return other
    matches: list[SourceFile] = [other for other in sources if other.path.name == Path(reference).name]
    return matches[0] if len(matches) == 1 else None


def rewrite_references(source: SourceFile, sources: Sequence[SourceFile]) -> str:
    """Returns the body with references to other instruction files pointed at files that exist for Claude.

    A reference to a file that has a rule file now points at that rule file. A reference to a
    skipped file points at the source file. Inside a Markdown link the new target is a path relative
    to the rule file; elsewhere it is a path from the repository root.
    """

    def replace(match: re.Match[str]) -> str:
        referenced: SourceFile | None = find_referenced_source(source, match.group(1), sources)
        if referenced is None:
            return match.group(0)
        destination: Path = referenced.target if referenced.apply_to else referenced.path
        if match.string[max(0, match.start() - 1) : match.start()] == "[":
            return destination.name
        in_link: bool = match.string[max(0, match.start() - 2) : match.start()] == "]("
        if in_link:
            return Path(os.path.relpath(destination, source.target.parent)).as_posix()
        return destination.relative_to(REPO_ROOT).as_posix()

    return INSTRUCTION_REF.sub(replace, source.body)


def render(source: SourceFile, sources: Sequence[SourceFile]) -> str:
    """Returns the full text of the rule file for one source file."""
    assert source.apply_to is not None
    paths: list[str] = [] if set(source.apply_to) <= ALWAYS_ON_PATTERNS else source.apply_to
    header: str = ""
    if paths:
        quoted: str = "\n".join(f'  - "{pattern}"' for pattern in paths)
        header = f"---\npaths:\n{quoted}\n---\n\n"
    marker: str = f"{MARKER_PREFIX}{source.relative}. Do not edit; edit the source file and run `make claude-rules`. -->\n"
    return f"{header}{marker}\n{rewrite_references(source, sources).lstrip()}"


def collect_sources() -> list[SourceFile]:
    """Returns all instruction files under .github/instructions/, sorted by path."""
    return [parse_source(path) for path in sorted(SOURCE_DIR.rglob(f"*{SOURCE_SUFFIX}"))]


def is_generated(path: Path) -> bool:
    """Returns True when a rule file carries the marker written by this script."""
    return MARKER_PREFIX in path.read_text(encoding="utf-8")


def sync(check_only: bool) -> int:
    """Writes or checks the rule files. Returns the number of files that are or were out of date."""
    sources: list[SourceFile] = collect_sources()
    expected: dict[Path, str] = {s.target: render(s, sources) for s in sources if s.apply_to}
    skipped: list[SourceFile] = [s for s in sources if not s.apply_to]

    problems: list[str] = []
    for target, text in expected.items():
        current: str | None = target.read_text(encoding="utf-8") if target.exists() else None
        if current == text:
            continue
        if current is not None and not is_generated(target):
            problems.append(f"{target.relative_to(REPO_ROOT)}: exists and is not generated; not overwritten")
            continue
        problems.append(f"{target.relative_to(REPO_ROOT)}: {'missing' if current is None else 'out of date'}")
        if not check_only:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text, encoding="utf-8")

    stale: list[Path] = (
        [p for p in sorted(TARGET_DIR.rglob("*.md")) if p not in expected and is_generated(p)] if TARGET_DIR.exists() else []
    )
    for path in stale:
        problems.append(f"{path.relative_to(REPO_ROOT)}: no source file; {'would be removed' if check_only else 'removed'}")
        if not check_only:
            path.unlink()

    for line in problems:
        print(line)
    for source in skipped:
        print(f"skipped (no applyTo): {source.relative}", file=sys.stderr)

    if check_only and problems:
        print("Claude rules are out of date. Run `make claude-rules` and commit the result.", file=sys.stderr)
    elif not problems:
        print(f"{len(expected)} Claude rule files are up to date.")
    return len(problems)


def main(argv: Sequence[str] | None = None) -> int:
    """Entry point. Exits with 1 in --check mode when any rule file is out of date."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="change nothing; exit 1 if rule files are out of date")
    args = parser.parse_args(argv)
    problems: int = sync(check_only=args.check)
    return 1 if args.check and problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
